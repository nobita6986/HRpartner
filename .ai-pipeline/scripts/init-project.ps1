    }

    # -------------------------------------------------- OpenCode
    function Write-OpenCode {
        param([string]$Root)
        $rel = Get-RelPath -From $Root -To (Join-Path $Root ".ai-pipeline")
        $content = @"
# Auto-generated by .ai-pipeline/scripts/init-project.ps1 - DO NOT EDIT.
# Source of truth: $($rel.Replace('\\','/'))

This repo follows the HRP 3-tier pipeline (Planner → Engineer → Auditor).
Source of truth: $($rel).

Roles: see $($rel)/agents/{planner,engineer,auditor}.md
Role prompts (full): see $($rel)/tier{1,2,3}.md
Hard rules:
- Tier 1: contracts only.
- Tier 2: no self-audit; evidence must be real.
- Tier 3: no fix, no contract change; tự reproduce verify commands.
Skills: see $($rel)/SKILL-ECOSYSTEM.md
Workflow: see $($rel)/PIPELINE-GUIDE.md
"@
        $out = Join-Path $Root "OPENCODE.md"
        Write-Utf8 -Path $out -Content $content
        Write-Status OK "OpenCode → $out"
    }

    # Dispatch
    foreach ($t in $targets) {
        switch ($t) {
            "cursor"        { Write-Cursor -Root $resolvedProject }
            "antigravity"   { Write-Antigravity -Root $resolvedProject }
            "claude-code"   { Write-ClaudeCode -Root $resolvedProject }
            "vscode-copilot"{ Write-VSCodeCopilot -Root $resolvedProject }
            "opencode"      { Write-OpenCode -Root $resolvedProject }
        }
    }

    Write-Status TITLE "Done."
    Write-Status INFO "Source of truth (.ai-pipeline/) is intact; only root wrappers generated."
    exit 0
}
catch {
    Write-Status FAIL "Init failed: $($_.Exception.Message)"
    exit 2
}
