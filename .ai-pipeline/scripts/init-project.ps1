        $content = @"
# Auto-generated by .ai-pipeline/scripts/init-project.ps1 - DO NOT EDIT.
# Source of truth: $($rel.Replace('\\','/'))

## Repository Instructions
This repo runs the HRP 3-tier pipeline. Source of truth at $($rel).

## Roles
| Tier | Role | Manifest |
|---|---|---|
| 1 | Planner | $($rel)/agents/planner.md |
| 2 | Engineer | $($rel)/agents/engineer.md |
| 3 | Auditor | $($rel)/agents/auditor.md |
| - | Tier 1 prompt | $($rel)/tier1.md |
| - | Tier 2 prompt | $($rel)/tier2.md |
| - | Tier 3 prompt | $($rel)/tier3.md |

## Iron Rules
1. Tier 1: contracts only. No code.
2. Tier 2: no self-audit.
